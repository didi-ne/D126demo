#define T180BV_RESET_PIN "PB.6"
static struct gpio_desc reset;

static int panel_prepare(void)
{
    panel_get_gpio(&reset, T180BV_RESET_PIN);

    panel_gpio_set_value(&reset, 1);
    aic_delay_ms(10);
    panel_gpio_set_value(&reset, 0);
    aic_delay_ms(100);
    panel_gpio_set_value(&reset, 1);
    aic_delay_ms(120);

    return 0;
}

static int panel_enable(struct aic_panel *panel)
{
    struct panel_dbi_commands *commands = &panel->dbi->commands;
    struct spi_cfg *spi = panel->dbi->spi;

    panel_di_enable(panel, 0);
    panel_dbi_commands_execute(panel, commands);

    spi->code[0] = 0x32;
    panel_di_enable(panel, 0);

    panel_de_timing_enable(panel, 0);
    panel_backlight_enable(panel, 0);
    return 0;
}

static struct aic_panel_funcs t180bv_funcs = {
    .prepare = panel_prepare,
    .enable = panel_enable,
    .disable = panel_default_disable,
    .unprepare = panel_default_unprepare,
    .register_callback = panel_register_callback,
};

static struct display_timing t180bv_timing = {
    .pixelclock   = 9000000,

    .hactive      = 360,
    .hback_porch  = 10,
    .hfront_porch = 10,
    .hsync_len    = 10,

    .vactive      = 360,
    .vback_porch  = 10,
    .vfront_porch = 10,
    .vsync_len    = 10,
};

static struct spi_cfg spi = {
    .qspi_mode = 0,
    .vbp_num   = 0,
    .code1_cfg = 0,
    .code      = { 0x02, 0x00, 0x00 },
};

static struct panel_dbi dbi = {
    .type = SPI,
    .format = SPI_4SDA_RGB565,
    .first_line = 0x2C,
    .other_line = 0x3C,
    .spi = &spi,
    .commands = {
        .buf = t180bv_commands,
        .len = ARRAY_SIZE(t180bv_commands),
    }
};

struct aic_panel dbi_t180bv = {
    .name = "panel-t180bv",
    .timings = &t180bv_timing,
    .funcs = &t180bv_funcs,
    .dbi = &dbi,
    .connector_type = AIC_DBI_COM,
};
